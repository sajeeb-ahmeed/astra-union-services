/**
 * Generator for db/migrations/054_service_versions_publish.sql
 *
 * Why this migration exists: application creation validates against the
 * code's latest schema version, looked up in the service_versions table.
 * Until BUNDLE-06 the only publisher of service_versions rows was
 * scripts/seed.ts, which must never run against production. Databases that
 * were only migrated (never seeded) therefore kept BUNDLE-05-era schema
 * versions and BUNDLE-06 application creation failed with
 * 422 SCHEMA_UNAVAILABLE for 33 of 47 services.
 *
 * This generator emits a data-only migration that publishes exactly the
 * rows seed.ts would insert for service_versions — byte-identical
 * schema_json (stableSchemaJson) and schema_hash (sha256 hex of that
 * json) — using the tree's own @astra/shared-schemas build, the same
 * import seed.ts uses:
 *   (a) the current version of every service (getServiceSchema),
 *   (b) every historical version (allServiceSchemaVersions),
 *   (c) version 0 = the catalog preview schema (getCatalogPreviewSchema).
 *
 * The publish is catalog-gated (EXISTS service_catalog): service_versions
 * has an FK to service_catalog, which only seed/initialize populate —
 * migrations run first, so on a migrate-only fresh database this
 * migration must be a no-op rather than an FK violation (the API test
 * suite's isolated fixtures run migrate-only; fresh cPanel installs get
 * the same rows from scripts/initialize.ts, which publishes catalog +
 * versions itself).
 *
 * The migration is idempotent (INSERT ... ON CONFLICT DO NOTHING staged
 * through a temp table) and fails loudly on drift, mirroring seed.ts: if
 * any code-known operational (service_no, version) already exists with a
 * different schema_hash, a DO block raises and the migration transaction
 * rolls back. Like seed.ts, the drift guard covers current + historical
 * versions (version > 0) only: seed never drift-checks the version-0
 * catalog preview row, whose content legitimately changes when catalog
 * display names change (e.g. migration 053's "Trade License" sync
 * changed service 42's preview) and which application validation never
 * reads. Version-0 rows are insert-if-absent only, exactly as in seed.
 * Both migration runners (scripts/migrate.ts and
 * scripts/migrate-cpanel.ts) execute each file inside a single
 * transaction on one connection, so the temp table + DO block pattern is
 * safe. NOTE: the emitted SQL must never contain the literal "astra_app"
 * (migrate-cpanel.ts rewrites that identifier for single-role cPanel).
 *
 * Usage: node scripts/generate-migration-054.mjs
 * Writes db/migrations/054_service_versions_publish.sql (deterministic:
 * rows sorted by service_no, then version).
 */
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import {
  serviceCatalog,
  getServiceSchema,
  getCatalogPreviewSchema,
  stableSchemaJson,
  allServiceSchemaVersions,
} from "@astra/shared-schemas";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const outPath = path.join(root, "db/migrations/054_service_versions_publish.sql");

// Collect exactly the rows seed.ts publishes, in seed's order of discovery.
const rows = new Map(); // key `${no}:${version}` -> {no, version, json, hash}
function addRow(no, version, schema) {
  const json = stableSchemaJson(schema);
  const hash = createHash("sha256").update(json).digest("hex");
  const key = `${no}:${version}`;
  const existing = rows.get(key);
  if (existing && existing.hash !== hash)
    throw new Error(
      `Generator conflict: service ${no} version ${version} produced two different hashes (${existing.hash} vs ${hash}).`,
    );
  rows.set(key, { no, version, json, hash });
}
for (const service of serviceCatalog) {
  const no = service.service_no;
  const schema = getServiceSchema(no);
  addRow(no, schema.version, schema);
  for (const historical of allServiceSchemaVersions.filter(
    (item) => item.serviceNo === no && item.version !== schema.version,
  ))
    addRow(no, historical.version, historical);
  addRow(no, 0, getCatalogPreviewSchema(no));
}
const sorted = [...rows.values()].sort(
  (a, b) => a.no - b.no || a.version - b.version,
);

const sqlString = (s) => {
  if (s.includes("\0")) throw new Error("NUL byte in schema json; cannot emit.");
  // Dollar-quote with a tag guaranteed absent from the payload.
  let tag = "svjson";
  while (s.includes(`$${tag}$`)) tag += "x";
  return `$${tag}$${s}$${tag}$`;
};

const lines = [];
lines.push(`-- 054_service_versions_publish.sql`);
lines.push(`-- GENERATED by scripts/generate-migration-054.mjs — do not edit by hand.`);
lines.push(`--`);
lines.push(`-- Data-only publish of the BUNDLE-06 service schema versions into`);
lines.push(`-- service_versions, byte-identical to what scripts/seed.ts inserts`);
lines.push(`-- (same @astra/shared-schemas build, same stableSchemaJson + sha256`);
lines.push(`-- recipe). Fixes production databases that were migrated but never`);
lines.push(`-- seeded: their service_versions rows predated BUNDLE-06, so`);
lines.push(`-- application creation failed with 422 SCHEMA_UNAVAILABLE for every`);
lines.push(`-- service whose latest schema version was not yet in the table.`);
lines.push(`--`);
lines.push(`-- Idempotent: re-running inserts nothing and changes nothing.`);
lines.push(`-- Catalog-gated: rows are published only for services present in`);
lines.push(`-- service_catalog. Migrations run BEFORE seed/initialize populates`);
lines.push(`-- the catalog, so on a migrate-only fresh database this migration`);
lines.push(`-- is a no-op (service_versions carries an FK to service_catalog);`);
lines.push(`-- initialize.ts publishes the same rows itself on fresh installs.`);
lines.push(`-- Drift-guarded (mirrors seed.ts): if any code-known operational`);
lines.push(`-- (service_no, version) with version > 0 already exists with a`);
lines.push(`-- different schema_hash, this migration raises and its transaction`);
lines.push(`-- rolls back. Version-0 preview rows are insert-if-absent only,`);
lines.push(`-- exactly as in seed.ts (their content follows catalog display`);
lines.push(`-- names — see migration 053 — and validation never reads them).`);
lines.push(`-- Rows published: ${sorted.length} (${serviceCatalog.length} services: current + historical + version-0 preview).`);
lines.push(``);
lines.push(`CREATE TEMPORARY TABLE service_versions_expected_054 (`);
lines.push(`  service_no integer NOT NULL,`);
lines.push(`  version integer NOT NULL,`);
lines.push(`  schema_json jsonb NOT NULL,`);
lines.push(`  schema_hash text NOT NULL,`);
lines.push(`  PRIMARY KEY (service_no, version)`);
lines.push(`) ON COMMIT DROP;`);
lines.push(``);
lines.push(`INSERT INTO service_versions_expected_054 (service_no, version, schema_json, schema_hash) VALUES`);
const valueLines = sorted.map(
  (r) =>
    `  (${r.no}, ${r.version}, ${sqlString(r.json)}, '${r.hash}')`,
);
lines.push(valueLines.join(",\n") + ";");
lines.push(``);
lines.push(`INSERT INTO service_versions (service_no, version, schema_json, schema_hash)`);
lines.push(`SELECT e.service_no, e.version, e.schema_json, e.schema_hash`);
lines.push(`FROM service_versions_expected_054 e`);
lines.push(`WHERE EXISTS (SELECT 1 FROM service_catalog c WHERE c.service_no = e.service_no)`);
lines.push(`ON CONFLICT DO NOTHING;`);
lines.push(``);
lines.push(`DO $$`);
lines.push(`DECLARE`);
lines.push(`  drifted text;`);
lines.push(`BEGIN`);
lines.push(`  SELECT string_agg(e.service_no || ':' || e.version, ', ' ORDER BY e.service_no, e.version)`);
lines.push(`    INTO drifted`);
lines.push(`    FROM service_versions_expected_054 e`);
lines.push(`    JOIN service_versions v`);
lines.push(`      ON v.service_no = e.service_no AND v.version = e.version`);
lines.push(`   WHERE e.version > 0 AND v.schema_hash <> e.schema_hash`);
lines.push(`     AND EXISTS (SELECT 1 FROM service_catalog c WHERE c.service_no = e.service_no);`);
lines.push(`  IF drifted IS NOT NULL THEN`);
lines.push(`    RAISE EXCEPTION 'Immutable schema drift detected for service_versions (service:version): %; publish a new schema version instead of rewriting history.', drifted;`);
lines.push(`  END IF;`);
lines.push(`END $$;`);
lines.push(``);

fs.writeFileSync(outPath, lines.join("\n"));
console.log(
  `Wrote ${path.relative(root, outPath)} with ${sorted.length} expected rows for ${serviceCatalog.length} services.`,
);
