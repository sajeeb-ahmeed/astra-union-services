import fs from "node:fs";
const file = "apps/api/openapi.json";
const api = JSON.parse(fs.readFileSync(file, "utf8"));
const code = { type: "string", pattern: "^[a-z0-9-]{3,30}$" };
const ref = { $ref: "#/components/schemas/GeographyInput" };
api.components.schemas.GeographyInput = {
  type: "object",
  additionalProperties: false,
  description:
    "Community dataset IDs, not official BBS codes. Complete five-level rural hierarchy required for citizen addresses. UNION offices require unionCode; wardCode optional. Urban offices stop at upazila (urban wards are not in this dataset). Server validates every parent and mapped office jurisdiction.",
  properties: Object.fromEntries(
    [
      "divisionCode",
      "districtCode",
      "upazilaCode",
      "unionCode",
      "wardCode",
    ].map((k) => [k, code]),
  ),
  required: ["divisionCode", "districtCode", "upazilaCode"],
};
api.components.schemas.GeographyItem = {
  type: "object",
  properties: {
    code,
    nameEn: { type: "string" },
    nameBn: { type: "string" },
    parentCode: code,
  },
  required: ["code", "nameEn", "nameBn"],
};
for (const level of ["divisions", "districts", "upazilas", "unions", "wards"]) {
  api.paths[`/api/v1/geography/${level}`] = {
    get: {
      summary: `List ${level} in the supplied Bangladesh geography dataset`,
      security: [],
      description:
        "Public read-only reference data; Cache-Control public,max-age=3600 and ETag. No participating office or official authorization is implied. Child queries are bounded by their required parent. Wards are derived rural records.",
      parameters:
        level === "divisions"
          ? []
          : [
              {
                name: "parentCode",
                in: "query",
                required: true,
                schema: code,
                description: "Immediate parent dataset code",
              },
            ],
      responses: {
        200: {
          description:
            "Valid parent with no children returns an empty items array.",
          content: {
            "application/json": {
              schema: {
                type: "object",
                properties: {
                  items: {
                    type: "array",
                    items: { $ref: "#/components/schemas/GeographyItem" },
                  },
                  total: { type: "integer" },
                  parentCode: code,
                },
                required: ["items", "total"],
              },
            },
          },
        },
        400: {
          description:
            "Missing, malformed, duplicated or unexpected query parameter",
        },
        404: {
          description:
            "Parent code does not exist in the immediate parent table",
        },
      },
    },
  };
}
api.paths["/api/v1/geography/metadata"] = {
  get: {
    summary: "Read dataset provenance, counts, hashes and coverage limitations",
    security: [],
    responses: {
      200: {
        description:
          "datasetId,source,sourceUrl,sourceDate,license,counts,coverage,fileSha256,upazilasWithoutUnions,limitations,identifiersAreOfficial:false,wardsDerived:true",
      },
      503: { description: "Dataset not initialized" },
    },
  },
};
function schemaAt(path, method) {
  return api.paths[path][method].requestBody.content["application/json"].schema;
}
for (const schema of [
  api.components.schemas.CitizenInput,
  schemaAt("/api/v1/auth/signup", "post"),
]) {
  schema.properties.geography = ref;
  schema.required = schema.required.filter((k) => k !== "syntheticReference");
  schema.properties.syntheticReference.description =
    "Optional compatibility field; omitted values receive a unique server-generated reference.";
}
for (const [path, method] of [
  ["/api/v1/owner/tenants", "post"],
  ["/api/v1/admin/office", "patch"],
  ["/api/v1/profile", "patch"],
]) {
  const schema = schemaAt(path, method);
  schema.properties.geography = ref;
  if (path !== "/api/v1/profile")
    schema.required = (schema.required ?? []).filter(
      (k) => !["division", "district", "upazila"].includes(k),
    );
  api.paths[path][method].responses["400"] = {
    description:
      "Invalid hierarchy, geographic jurisdiction or incompatible urban/rural scope",
  };
}
const signup = api.paths["/api/v1/auth/signup"].post;
signup.description =
  "Creates a persistent local account; no identity-provider verification. Geography is optional for legacy unmapped offices and mandatory for mapped offices. A supplied address must include all five rural levels and match the mapped office. syntheticReference is optional and generated by the server. Returns registered,verificationState,geography; sign in separately.";
signup.responses["400"] = {
  description:
    "Geography missing for mapped office, parent mismatch, incomplete rural hierarchy or office jurisdiction mismatch",
};
api.paths["/api/v1/profile"].get.description =
  "Includes geography|null from the current user's citizen record, under tenant RLS. Non-citizen users have no citizen geography.";
api.paths["/api/v1/profile"].patch.description +=
  " Optional geography updates the caller's citizen record with tenant and office jurisdiction validation. Other roles cannot set citizen geography.";
for (const name of [
  "divisionCode",
  "districtCode",
  "upazilaCode",
  "unionCode",
]) {
  const params = api.paths["/api/v1/offices"].get.parameters;
  if (!params.some((p) => p.name === name))
    params.push({
      name,
      in: "query",
      required: false,
      schema: code,
      description:
        "Exact dataset code filter, combined with all other office filters",
    });
}
api.paths["/api/v1/offices"].get.description +=
  " Items include geography|null and flat divisionCode,districtCode,upazilaCode,unionCode,wardCode; old offices remain unmapped until explicitly configured.";
fs.writeFileSync(file, JSON.stringify(api, null, 2) + "\n");
