export interface CatalogEntry {
  service_no: number;
  name_bn: string;
  name_en: string;
  category_en: string;
}

const catalogByNo = new Map<number, CatalogEntry>(
  (serviceCatalog as CatalogEntry[]).map((s) => [s.service_no, s]),
);
const seoByNo = new Map<number, ServiceSeo>(SERVICE_SEO.map((s) => [s.no, s]));
const seoBySlug = new Map<string, ServiceSeo>(SERVICE_SEO.map((s) => [s.slug, s]));

export function catalogEntry(no: number): CatalogEntry {
  const entry = catalogByNo.get(no);
  if (!entry) throw Error(`Unknown service number ${no}`);
  return entry;
}
export function serviceSeo(no: number): ServiceSeo {
  const entry = seoByNo.get(no);
  if (!entry) throw Error(`Missing SEO registry entry for service ${no}`);
  return entry;
}
export function serviceBySlug(slug: string): ServiceSeo | undefined {
  return seoBySlug.get(slug);
}
export function servicePath(no: number): string {
  return `/services/${serviceSeo(no).slug}`;
}
export function officePath(slug: string): string {
  return `/offices/${slug}`;
}
export function relatedServices(no: number): ServiceSeo[] {
  return serviceSeo(no).related.map((n) => serviceSeo(n));
}

