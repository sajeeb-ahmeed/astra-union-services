/**
 * Phase 4c (G13): a free public flow — religion → certificate type → deceased's name, attestor's name, mobile and
 * NID → a witness-statement PDF. It is a utility document, clearly badged, not an office certificate. The
 * religion and type options are the owner's list (migration 034); nothing the visitor enters is stored.
 */
type Req = express.Request & { auth?: Auth };
const wrap =
  (fn: (req: Req, res: express.Response) => Promise<unknown>) =>
  (req: Req, res: express.Response, next: express.NextFunction) =>
    Promise.resolve(fn(req, res)).catch(next);
const escape = (v: unknown) =>
  String(v ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);
const typeRow = (r: any) => ({
  id: r.id,
  religionBn: r.religion_bn,
  religionEn: r.religion_en,
  nameBn: r.name_bn,
  nameEn: r.name_en,
  active: r.active,
  sortOrder: r.sort_order,
});
const bnDigits = (v: string) => v.replace(/\d/g, (d) => "০১২৩৪৫৬৭৮৯"[Number(d)]);

