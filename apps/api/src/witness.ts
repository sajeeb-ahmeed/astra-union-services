export const publicWitnessRouter = express.Router();
publicWitnessRouter.get(
  "/public/witness/options",
  wrap(async (_req, res) => {
    const rows = (
      await pool.query("SELECT * FROM witness_certificate_types WHERE active ORDER BY religion_en, sort_order, name_en")
    ).rows;
    res.json({ items: rows.map(typeRow) });
  }),
);
const limiter = createRateLimiter({ limit: 10, windowMs: 60 * 60_000 });
publicWitnessRouter.post(
  "/public/witness",
  limiter,
  wrap(async (req, res) => {
    const d = z
      .object({
        typeId: z.string().uuid(),
        deceasedNameBn: z.string().trim().min(2).max(150),
        attestorNameBn: z.string().trim().min(2).max(150),
        mobile: z.string().max(40),
        nid: z.string().max(40),
      })
      .strict()
      .parse(req.body);
    const mobile = normalizeIdentifier("mobile", d.mobile);
    if (!mobile) fail(422, "IDENTIFIER_INVALID", "Enter an 11-digit Bangladeshi mobile number starting with 01.");
    // The guide's rule for this form: a 10- or 17-digit NID.
    const nid = normalizeIdentifier("nid", d.nid);
    if (!nid || ![10, 17].includes(nid.length)) fail(422, "IDENTIFIER_INVALID", "Enter a 10 or 17 digit NID number.");
    const type = (await pool.query("SELECT * FROM witness_certificate_types WHERE id=$1 AND active", [d.typeId])).rows[0];
    if (!type) fail(422, "WITNESS_TYPE_UNAVAILABLE", "Choose one of the listed certificate types.");
    const pdf = await renderHtmlPdf(
      witnessHtml({ type, deceasedNameBn: d.deceasedNameBn, attestorNameBn: d.attestorNameBn, mobile: mobile!, nid: nid!, generatedOn: new Date().toISOString().slice(0, 10) }),
    );
    res
      .type("application/pdf")
      .setHeader("Content-Disposition", 'attachment; filename="witness-statement.pdf"')
      .setHeader("Cache-Control", "no-store");
    res.send(pdf);
  }),
);

export const ownerWitnessRouter = express.Router();
const owner = (req: Req) => {
  if (req.auth?.role !== "owner") fail(403, "ROLE_DENIED", "This role is not permitted.");
  return req.auth!;
};
ownerWitnessRouter.get(
  "/owner/witness-types",
  wrap(async (req, res) => {
    owner(req);
    const rows = (await pool.query("SELECT * FROM witness_certificate_types ORDER BY religion_en, sort_order, name_en")).rows;
    res.json({ items: rows.map(typeRow) });
  }),
);
ownerWitnessRouter.post(
  "/owner/witness-types",
  wrap(async (req, res) => {
    const a = owner(req);
    const d = z
      .object({
        religionBn: z.string().trim().min(2).max(60),
        religionEn: z.string().trim().min(2).max(60),
        nameBn: z.string().trim().min(2).max(160),
        nameEn: z.string().trim().min(2).max(160),
        sortOrder: z.number().int().min(0).max(1000).default(0),
      })
      .strict()
      .parse(req.body);
    try {
      const row = (
        await pool.query(
          "INSERT INTO witness_certificate_types(religion_bn,religion_en,name_bn,name_en,sort_order,created_by) VALUES($1,$2,$3,$4,$5,$6) RETURNING *",
          [d.religionBn, d.religionEn, d.nameBn, d.nameEn, d.sortOrder, a.userId],
        )
      ).rows[0];
      res.status(201).json(typeRow(row));
    } catch (error: any) {
      if (error?.code === "23505") fail(409, "WITNESS_TYPE_EXISTS", "This certificate type already exists for this religion.");
      throw error;
    }
  }),
);
ownerWitnessRouter.patch(
  "/owner/witness-types/:id",
  wrap(async (req, res) => {
    owner(req);
    const id = z.string().uuid().parse(req.params.id);
    const d = z.object({ active: z.boolean() }).strict().parse(req.body);
    const row = (await pool.query("UPDATE witness_certificate_types SET active=$2 WHERE id=$1 RETURNING *", [id, d.active])).rows[0];
    if (!row) fail(404, "NOT_FOUND", "Certificate type not found.");
    res.json(typeRow(row));
  }),
);
